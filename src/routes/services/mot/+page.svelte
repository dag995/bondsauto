      <h2>MOT Testing</h2>
      <p>We can prepare your MOT for the testing centre, carrying out the complete range of statutory checks required by the DVSA, including:</p>
      <ul>
        <li>Lights and signalling: headlights, indicators, brake lights, hazards</li>
        <li>Steering and suspension: play, wear, and alignment</li>
        <li>Brakes: pads, discs, handbrake performance and efficiency</li>
        <li>Tyres and wheels: tread depth, condition, damage</li>
        <li>Bodywork and structure: corrosion, sharp edges, security</li>
        <li>Emissions: exhaust and environmental compliance</li>
        <li>Seatbelts, mirrors, wipers, horn: all the smaller items that catch drivers out</li>
        <li>Registration plates, VIN and vehicle identification</li>
      </ul>
      <p>You'll get a clear, jargon-free explanation of the results, and if anything needs attention, we'll talk you through your options before any work goes ahead.</p>
      
      <h2>Pre-MOT Health Checks</h2>
      <p>Don't wait for test day to find out something's wrong. Our pre-MOT check gives your car a thorough once-over against MOT standards, so you know exactly where you stand.</p>
      <p>What we look for:</p>
      <ul>
        <li>Worn brake pads, discs or fluid levels</li>
        <li>Tyre tread depth and uneven wear</li>
